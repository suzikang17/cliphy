// Shared date formatting for admin views.

// Date only — for pure DATE columns (trial_ends_at, monthly_count_reset_at).
export function formatDate(iso: string): string {
  return new Date(iso).toLocaleDateString("en-US", {
    year: "numeric",
    month: "short",
    day: "numeric",
  });
}

// Date + time — for timestamptz columns (created_at), useful for ops debugging.
export function formatDateTime(iso: string): string {
  return new Date(iso).toLocaleString("en-US", {
    year: "numeric",
    month: "short",
    day: "numeric",
    hour: "numeric",
    minute: "2-digit",
  });
}
